/* solitaire-rl site: the 1000-deal field, the method slider, recordings.
   All data comes from deals.js, generated by site/build_data.py from results/. */
(() => {
  const $ = (s, el = document) => el.querySelector(s);
  const $$ = (s, el = document) => [...el.querySelectorAll(s)];
  const reduce = matchMedia("(prefers-reduced-motion: reduce)");
  const D = window.SRL;

  /* ---------- recordings: play when seen (hero) or pointed at (tiles) ---------- */
  const media = D ? D.media : "mp4";
  const recSrc = (name) => `rec/${name}.${media}`;
  $$("video.rec").forEach((v) => {
    v.controls = false;
    v.addEventListener("error", () => fallback(v), true);
  });
  function fallback(v) {
    // A missing MP4 (built without ffmpeg) falls back to the GIF.
    const img = Object.assign(new Image(466, 380), {
      src: `rec/${v.dataset.rec}.gif`, alt: v.getAttribute("aria-label") || "", loading: "lazy",
    });
    img.className = "rec";
    v.replaceWith(img);
  }
  const play = (v) => { if (!reduce.matches) v.play().catch(() => {}); };
  const hero = $$(".hero video.rec");
  if ("IntersectionObserver" in window) {
    const io = new IntersectionObserver((es) => es.forEach((e) => {
      if (e.isIntersecting) play(e.target); else e.target.pause();
    }), { threshold: 0.3 });
    hero.forEach((v) => io.observe(v));
  } else hero.forEach(play);
  $$(".tile").forEach((t) => {
    const v = $("video", t);
    if (!v) return;
    t.tabIndex = 0;
    t.setAttribute("role", "button");
    t.setAttribute("aria-label", `Play: ${v.getAttribute("aria-label")}`);
    const on = () => { if (!reduce.matches) v.play().catch(() => {}); };
    const off = () => v.pause();
    t.addEventListener("pointerenter", (e) => { if (e.pointerType === "mouse") on(); });
    t.addEventListener("pointerleave", (e) => { if (e.pointerType === "mouse") off(); });
    t.addEventListener("focus", on);
    t.addEventListener("blur", off);
    t.addEventListener("click", () => {
      if (reduce.matches) { v.controls = true; }
      if (v.paused) v.play().catch(() => {}); else v.pause();
    });
    t.addEventListener("keydown", (e) => {
      if (e.key === "Enter" || e.key === " ") { e.preventDefault(); t.click(); }
    });
  });
  reduce.addEventListener?.("change", () => { if (reduce.matches) $$("video.rec").forEach((v) => v.pause()); });

  /* ---------- the method slider ---------- */
  const STAGES = [
    {
      clause: "Plain MaskablePPO plateaus", v: 11.8, sub: "MaskablePPO, 6M steps, compact POMDP",
      body: "Compact 132-dim observation, six million steps on CPU. Three million more steps changed nothing. Perfect information, the upper bound of what seeing every hidden card adds, reaches only 17.7%: observability is not the main bottleneck.",
      facts: ["Action masking: every legal move is reachable, illegal moves never are", "Losses are overwhelmingly no_progress_cycle", "One-hot 49k-dim observation: 0.000, untrainable at this budget"],
    },
    {
      clause: "Anchor it to the heuristic", v: 26.5, sub: "PPO + BC warm-start, 3M steps, compact + hint",
      body: "Show the heuristic's chosen action as extra observation features and warm-start the actor from a shape-matched Tanh behavior clone. Either alone: 0.114 and 0.142. Together: 0.265, above the perfect-info model at half its steps.",
      facts: ["compact_hint observation, 142 dims", "The Tanh clone matches the MaskablePPO actor; the earlier ReLU clone did not transfer", "At lr 3e-4 every run decays after about 3M steps"],
    },
    {
      clause: "Lower the rate, chain from the peak", v: 35.3, sub: "PPO amplified chain, about 8M steps",
      body: "At lr 1e-4 a 97%-accurate clone holds instead of decaying: 0.278. Then clone the champion, not the heuristic, and resume from each run's best checkpoint: 0.324, 0.328, 0.353. A fourth link measures 0.349; the chain has converged.",
      facts: ["A 512 by 2 net lands at 0.287: capacity is not the ceiling", "Seed replications land between 0.229 and 0.353", "Single-model ceiling at this budget: about 0.35"],
    },
    {
      clause: "Let three strong models vote", v: 38.0, sub: "Ensemble vote of 3, per-move majority",
      body: "A per-move majority over three strong checkpoints adds two to three points over the best member and saturates around 0.38. Every voter must be strong: mixing in weaker observation variants drops it to 0.321.",
      facts: ["Voting step by step averages out the diversity that wins deals", "Distilling the vote back into one net: 0.332"],
    },
    {
      clause: "Let every lineage try every deal", v: 62.5, sub: "Portfolio of 26 RL lineages, declared best-of-N",
      body: "Win-sets between lineages overlap only about 70%, so each solves deals the others cannot. A declared portfolio plays all 26 on every deal and keeps the best episode-observable outcome. QRDQN, 0.067 on its own, still wins five deals no other member does.",
      facts: ["64.5% with the heuristic as a member", "57.9% from the nine committed checkpoints", "About two more deals per new lineage: the union is saturating"],
    },
  ];
  const stage = $("#stage");
  if (stage) {
    const names = $$("#stagenames li");
    const parts = [$("#clause"), $("#stagebody"), $("#meter")];
    const setStage = (i, animate) => {
      const s = STAGES[i];
      const swap = () => {
        $("#clause").textContent = s.clause;
        $("#stagebody").textContent = s.body;
        $("#metervalue").textContent = `${s.v.toFixed(1)}%`;
        $("#metersub").textContent = s.sub;
        $("#meterfacts").replaceChildren(...s.facts.map((f) => Object.assign(document.createElement("li"), { textContent: f })));
        $("#meter").setAttribute("aria-label", `Win rate ${s.v.toFixed(1)}% against the heuristic's 41.4%`);
        $("#meterfill").style.setProperty("--v", s.v);
        names.forEach((n, k) => n.classList.toggle("on", k === i));
        stage.setAttribute("aria-valuetext", `${s.clause}, ${s.v.toFixed(1)}%`);
        parts.forEach((p) => p.classList.remove("fading"));
      };
      if (animate && !reduce.matches) {
        parts.forEach((p) => p.classList.add("fading"));
        setTimeout(swap, 140);
      } else swap();
    };
    stage.addEventListener("input", () => setStage(+stage.value, true));
    names.forEach((n) => n.addEventListener("click", () => { stage.value = n.dataset.i; setStage(+n.dataset.i, true); }));
    setStage(0, false);
  }

  /* ---------- the 1000-deal field ---------- */
  if (!D) return;
  const field = $("#field");
  const L = Object.fromEntries(D.layers.map((l) => [l.id, l]));
  const won = (l, s) => (l.out ? l.out[s] === "W" : l.member[s] >= 0);
  const OUT = { W: "win", C: "no-progress cycle", I: "no progress, idle", K: "conceded", T: "truncated at 500", N: "no moves" };

  const SHOWN = [
    { id: "heuristic", name: "Heuristic" },
    { id: "dqn", name: "Masked DQN" },
    { id: "ppo", name: "MaskablePPO" },
    { id: "perfect", name: "PPO, perfect info" },
    { id: "canon9", name: "Portfolio of 9" },
    { id: "p26", name: "Portfolio of 26" },
    { id: "versus", name: "Portfolio of 26 vs heuristic" },
  ];
  /* drawn on a canvas: 1000 squares, 40 a row (25 on a phone) */
  const ctx = field.getContext("2d");
  const state = new Uint8Array(D.n); // 0 off, 1 lit, 2 alt (heuristic only), 3 both
  let geo = null, hover = -1;
  const css = (v) => getComputedStyle(document.documentElement).getPropertyValue(v).trim();
  function draw() {
    const W = field.clientWidth;
    if (!W) return;
    const c = innerWidth <= 700 ? 25 : 40, gap = 2;
    const cell = (W - gap * (c - 1)) / c, rows = Math.ceil(D.n / c);
    const H = Math.round(rows * cell + gap * (rows - 1));
    const dpr = window.devicePixelRatio || 1;
    if (field.width !== Math.round(W * dpr) || field.height !== Math.round(H * dpr)) {
      field.style.height = `${H}px`;
      field.width = Math.round(W * dpr);
      field.height = Math.round(H * dpr);
    }
    geo = { c, cell, gap };
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, W, H);
    const litColour = { heuristic: "--c-heur", dqn: "--c-rl", ppo: "--c-rl", perfect: "--c-rl" }[current] || "--c-port";
    const colours = [css("--c-off"), css(litColour), css("--c-heur"), css("--c-both")];
    for (let s = 0; s < D.n; s++) {
      ctx.fillStyle = colours[state[s]];
      ctx.fillRect((s % c) * (cell + gap), Math.floor(s / c) * (cell + gap), cell, cell);
    }
    const ring = (s, colour, w) => {
      ctx.strokeStyle = colour;
      ctx.lineWidth = w;
      ctx.strokeRect((s % c) * (cell + gap) - w / 2, Math.floor(s / c) * (cell + gap) - w / 2, cell + w, cell + w);
    };
    if (hover >= 0 && hover !== sel) ring(hover, css("--ink"), 2);
    ring(sel, css("--accent"), 3);
  }
  const at = (e) => {
    if (!geo) return -1;
    const r = field.getBoundingClientRect(), step = geo.cell + geo.gap;
    const col = Math.floor((e.clientX - r.left) / step), row = Math.floor((e.clientY - r.top) / step);
    const s = row * geo.c + col;
    return col >= 0 && col < geo.c && row >= 0 && s < D.n ? s : -1;
  };
  field.addEventListener("pointermove", (e) => { const s = at(e); if (s !== hover) { hover = s; draw(); } });
  field.addEventListener("pointerleave", () => { hover = -1; draw(); });
  if ("ResizeObserver" in window) new ResizeObserver(() => draw()).observe(field);
  else addEventListener("resize", draw);
  matchMedia("(prefers-color-scheme: light)").addEventListener?.("change", () => draw());

  const layersEl = $("#layers");
  let current = "p26";
  const buttons = SHOWN.map((o) => {
    const b = document.createElement("button");
    b.type = "button";
    b.setAttribute("role", "radio");
    b.textContent = o.name;
    b.dataset.id = o.id;
    b.addEventListener("click", () => show(o.id));
    layersEl.append(b);
    return b;
  });
  layersEl.addEventListener("keydown", (e) => {
    const i = SHOWN.findIndex((o) => o.id === current);
    const d = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key];
    if (!d) return;
    e.preventDefault();
    const n = (i + d + SHOWN.length) % SHOWN.length;
    show(SHOWN[n].id);
    buttons[n].focus();
  });

  const pct = (n) => `${((100 * n) / D.n).toFixed(1)}%`;
  function show(id) {
    current = id;
    buttons.forEach((b) => {
      const on = b.dataset.id === id;
      b.setAttribute("aria-checked", on);
      b.tabIndex = on ? 0 : -1;
    });
    const legend = $("#legend");
    if (id === "versus") {
      const h = L.heuristic, p = L.p26;
      let both = 0, rl = 0, he = 0;
      for (let s = 0; s < D.n; s++) {
        const a = won(p, s), b = won(h, s);
        state[s] = a && b ? 3 : a ? 1 : b ? 2 : 0;
        both += a && b; rl += a && !b; he += b && !a;
      }
      field.setAttribute("aria-label", `The 1000 benchmark deals: ${both} won by both, ${rl} only by the RL portfolio, ${he} only by the heuristic`);
      $("#count").innerHTML = `<b>${both + rl + he}</b> of 1000 deals won by one or the other`;
      legend.innerHTML = `<span class="k both"></span>${both} by both <span class="k lit"></span>${rl} only by the RL portfolio <span class="k alt"></span>${he} only by the heuristic`;
    } else {
      const l = L[id];
      let n = 0;
      for (let s = 0; s < D.n; s++) { const w = won(l, s); state[s] = w ? 1 : 0; n += w; }
      field.setAttribute("aria-label", `The 1000 benchmark deals, ${n} won by ${l.label}`);
      $("#count").innerHTML = `<b>${n}</b> of 1000 deals won, <b>${pct(n)}</b>`;
      legend.innerHTML = `${l.label}. Source: <code>${l.source}</code>`;
    }
    draw();
  }

  /* inspector */
  const seedIn = $("#seed");
  let sel = 47;
  const ROWS = ["heuristic", "dqn", "ppo", "perfect", "canon9", "p26", "p26h", "heuristic3", "random"];
  function select(s, fromInput) {
    if (!Number.isFinite(s)) return;
    sel = Math.max(0, Math.min(D.n - 1, Math.round(s)));
    if (!fromInput) seedIn.value = sel;
    draw();
    const tb = $("#perdeal tbody");
    tb.replaceChildren(...ROWS.map((id) => {
      const l = L[id];
      const tr = document.createElement("tr");
      const w = won(l, sel);
      let res;
      if (l.out) {
        res = `${OUT[l.out[sel]] || l.out[sel]}, ${l.moves[sel]} moves`;
      } else {
        res = w ? `win, by ${l.members[l.member[sel]]}` : "no member wins";
      }
      tr.className = w ? "w" : "";
      const th = document.createElement("th");
      th.scope = "row";
      th.textContent = l.label;
      const td = document.createElement("td");
      td.textContent = res;
      tr.append(th, td);
      return tr;
    }));
    renderRec(0);
  }
  function renderRec(k) {
    const box = $("#dealrec");
    const recs = D.recordings[sel] || [];
    box.replaceChildren();
    if (!recs.length) {
      const p = document.createElement("p");
      p.className = "quiet";
      p.textContent = `No recording of deal ${sel}. Recorded deals: ${Object.keys(D.recordings).join(", ")}.`;
      box.append(p);
      return;
    }
    const r = recs[k];
    let m;
    if (media === "mp4") {
      m = document.createElement("video");
      Object.assign(m, { src: recSrc(r.name), poster: `rec/${r.name}.jpg`, muted: true, loop: true, playsInline: true });
      m.width = 466; m.height = 380;
      m.setAttribute("aria-label", `${r.label} on deal ${sel}`);
      m.addEventListener("error", () => fallback(m));
      if (reduce.matches) m.controls = true; else m.play().catch(() => {});
    } else {
      m = Object.assign(new Image(466, 380), { src: recSrc(r.name), alt: `${r.label} on deal ${sel}` });
    }
    m.dataset.rec = r.name;
    m.className = "rec";
    const side = document.createElement("div");
    const h = document.createElement("p");
    h.textContent = `Recorded on deal ${sel}`;
    h.className = "rec-head";
    side.append(h);
    recs.forEach((x, i) => {
      const b = document.createElement("button");
      b.type = "button";
      b.className = "rec-pick";
      b.setAttribute("aria-pressed", i === k);
      b.textContent = `${x.label}: ${x.outcome.replace(/_/g, " ")}`;
      b.addEventListener("click", () => renderRec(i));
      side.append(b);
    });
    box.append(m, side);
  }
  field.addEventListener("click", (e) => { const s = at(e); if (s >= 0) select(s); });
  seedIn.addEventListener("input", () => { if (seedIn.value !== "") select(+seedIn.value, true); });
  seedIn.addEventListener("change", () => { seedIn.value = sel; });
  $("#prev").addEventListener("click", () => select((sel + D.n - 1) % D.n));
  $("#next").addEventListener("click", () => select((sel + 1) % D.n));

  show(current);
  select(sel);

  /* ---------- entrances: heading, text, picture, staggered ---------- */
  // Phones get the content at once: the page is long there and reveals only add waiting.
  if (!reduce.matches && "IntersectionObserver" in window && innerWidth > 700) {
    const groups = $$("main > section:not(.hero), .foot");
    groups.forEach((g) => {
      const parts = $$(":scope h2:not(.vh), :scope h3, :scope > p, :scope .deals-text > *, :scope .field, :scope .inspect, :scope .deal-rec, :scope .split-text, :scope .split-ui, :scope .stages, :scope figure, :scope .table-scroll, :scope .tile, :scope .local-text > *, :scope .cols > *, :scope .repro-rows > *, :scope .close-actions, :scope .foot-cols > *, :scope .foot-mark", g);
      parts.forEach((p, i) => { p.classList.add("rise"); p.style.setProperty("--d", `${Math.min(i, 8) * 70}ms`); });
    });
    const io = new IntersectionObserver((es) => es.forEach((e) => {
      if (e.isIntersecting) { $$(".rise", e.target).forEach((p) => p.classList.add("in")); io.unobserve(e.target); }
    }), { rootMargin: "0px 0px -10% 0px" });
    groups.forEach((g) => io.observe(g));
  }
})();
